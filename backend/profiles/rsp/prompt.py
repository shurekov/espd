def build_rsp_system_prompt(rule_id: str) -> str:
    if rule_id not in RSP_RULE_PROMPTS:
        raise ValueError(f"Неизвестное правило RSP: {rule_id}")

    return (
            RSP_BASE_PROMPT
            + f"\nКонкретное правило {rule_id}:\n"
            + RSP_RULE_PROMPTS[rule_id]
    ).strip()


