def build_opr_system_prompt(rule_id: str) -> str:
    if rule_id not in OPR_RULE_PROMPTS:
        raise ValueError(f"Неизвестное правило OPR: {rule_id}")

    return (
            OPR_BASE_PROMPT
            + f"\nКонкретное правило {rule_id}:\n"
            + OPR_RULE_PROMPTS[rule_id]
    ).strip()