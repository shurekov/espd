def build_rop_system_prompt(rule_id: str) -> str:
    if rule_id not in ROP_RULE_PROMPTS:
        raise ValueError(f"Неизвестное правило ROP: {rule_id}")

    return (
            ROP_BASE_PROMPT
            + f"\nКонкретное правило {rule_id}:\n"
            + ROP_RULE_PROMPTS[rule_id]
    ).strip()